def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--from", dest="source", type=Path, help="a saved `gh api` answer instead of asking GitHub")
    ap.add_argument("--date", default=datetime.datetime.now(datetime.timezone.utc).date().isoformat())
    ap.add_argument("--out", type=Path, default=ROOT)
    args = ap.parse_args()
    by = items(parse(args.source.read_text() if args.source else fetch()))
    site = args.out / "site" / "pointe" / "roadmap" / "index.html"
    site.parent.mkdir(parents=True, exist_ok=True)
    (args.out / "ROADMAP.md").write_text(markdown(by, args.date))
    site.write_text(page(by, args.date))
    print(f"roadmap: {sum(map(len, by.values()))} items ({', '.join(f'{s} {len(by[s])}' for s in SECTIONS)}), votes as of {args.date}")


if __name__ == "__main__":
    main()
