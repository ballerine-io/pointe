"""Write ROADMAP.md and the site's roadmap page (site/pointe/roadmap/index.html) from the `roadmap` issues.

    python3 tools/roadmap.py                ask GitHub with `gh api` (signed in), write both files
    python3 tools/roadmap.py --from FILE    read a saved answer instead (the REST issues list as JSON): no network
    --date YYYY-MM-DD                       the date the votes are shown as of (default: today, UTC)
    --out DIR                               write under DIR instead of this repository

An item is an issue labelled `roadmap`. Its section is its `horizon/now`, `horizon/next` or `horizon/later` label (none:
Later); closed as completed, it is Done; closed as not planned, it is left out. Each section is sorted by 👍 reactions,
most first. The page is a snapshot of those counts: it makes no request of its own (CLAUDE.md, "Supply chain"), and each
item links to its issue to vote. Issue titles are written by anyone who can open an issue, so both outputs escape them.
"""

import argparse
import datetime
import html
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "ballerine-io/pointe"
ISSUES = f"https://github.com/{REPO}/issues"
IDEAS = f"https://github.com/{REPO}/discussions/categories/ideas"
SECTIONS = ("Now", "Next", "Later", "Done")
INTRO = {
    "Now": "Being worked on, or ready to pick up now.",
    "Next": "After what is in Now. The approach is clear.",
    "Later": "Needs a design, an owner decision, or something outside Pointe first.",
    "Done": "Shipped. Closed as completed.",
}
TAGS = ("area/", "platform/")
OPEN_TO = ("good first issue", "help wanted")


def fetch() -> str:
    """Every issue labelled `roadmap`, open and closed, as `gh api` prints them (one JSON array per page)."""
    return subprocess.run(["gh", "api", "--paginate", f"repos/{REPO}/issues?labels=roadmap&state=all&per_page=100"],
                          capture_output=True, text=True, check=True, timeout=120).stdout


def parse(text: str) -> list[dict]:
    """The issues in `gh api --paginate` output: one or more JSON arrays, back to back."""
    out, decoder, i = [], json.JSONDecoder(), 0
    while i < len(text):
        if text[i].isspace():
            i += 1
            continue
        page, i = decoder.raw_decode(text, i)
        out.extend(page)
    return out


def items(issues: list[dict]) -> dict[str, list[dict]]:
    """{section: [item, ...]}, each list sorted by votes (most first), then by issue number."""
    by = {s: [] for s in SECTIONS}
    for issue in issues:
        labels = [label["name"] for label in issue.get("labels", [])]
        if "pull_request" in issue or "roadmap" not in labels:
            continue
        if issue["state"] == "closed":
            if issue.get("state_reason") != "completed":
                continue
            section = "Done"
        else:
            section = next((s for s in ("Now", "Next", "Later") if f"horizon/{s.lower()}" in labels), "Later")
        by[section].append({
            "number": int(issue["number"]),
            "title": issue["title"].strip(),
            "votes": int(issue.get("reactions", {}).get("+1", 0)),
            "tags": sorted(name for name in labels if name.startswith(TAGS)),
            "open_to": [name for name in OPEN_TO if name in labels],
        })
    for section in by.values():
        section.sort(key=lambda it: (-it["votes"], it["number"]))
    return by


def md_text(s: str) -> str:
    """A title as Markdown link text: nothing in it can close the link, start markup, or become HTML."""
    s = re.sub(r"([\\`*_\[\]])", r"\\\1", s)
    return s.replace("<", "&lt;").replace(">", "&gt;")


def markdown(by: dict[str, list[dict]], date: str) -> str:
    lines = [
        "<!-- Generated by tools/roadmap.py from the issues labelled `roadmap`. Change the issues, then run it again; do not edit this file. -->",
        "# Roadmap",
        "",
        "What may come next in Pointe, and how you can move it. Also on the site: https://eng.ballerine.com/pointe/roadmap/",
        "",
        "## How it works",
        "",
        "- **Vote** with a 👍 reaction on an item's issue. Each section below is sorted by 👍. A \"+1\" comment is not counted.",
        f"- **Propose** something new in [Discussions → Ideas]({IDEAS}). An idea that gathers support becomes a roadmap issue.",
        "- **Triage.** The maintainers read new ideas and votes about once a week, and move items between Now, Next and Later "
        "with the labels `horizon/now`, `horizon/next` and `horizon/later`. Votes inform the order; they do not decide it alone.",
        "- **No dates.** Pointe is community-supported, on a best-effort basis ([Support](README.md#support)).",
        "- **Build one.** Items open to contributors say *good first issue* or *help wanted*. Start with "
        "[CONTRIBUTING.md](CONTRIBUTING.md), and comment on the issue before you start something large.",
        "",
        f"Votes as of {date}.",
    ]
    for section in SECTIONS:
        lines += ["", f"## {section}", "", INTRO[section], ""]
        if not by[section]:
            lines.append("Nothing here yet.")
        for it in by[section]:
            extra = "".join(f" · {', '.join(group)}" for group in (it["tags"], it["open_to"]) if group)
            lines.append(f"- 👍 {it['votes']} · [{md_text(it['title'])}]({ISSUES}/{it['number']}) (#{it['number']}){extra}")
    return "\n".join(lines) + "\n"


def page(by: dict[str, list[dict]], date: str) -> str:
    esc = html.escape
    parts = []
    for section in SECTIONS:
        rows = []
        for it in by[section]:
            tags = "".join(f'<span class="pg-tag">{esc(t)}</span>' for t in it["tags"])
            tags += "".join(f'<span class="pg-tag pg-tag--open">{esc(t)}</span>' for t in it["open_to"])
            url = f"{ISSUES}/{it['number']}"
            votes = "vote" if it["votes"] == 1 else "votes"
            rows.append(
                f'      <li class="pg-item">\n'
                f'        <p class="pg-votes"><span>{it["votes"]}</span> <span class="pg-small">👍 {votes}</span></p>\n'
                f'        <div><p class="pg-item-title"><a href="{url}">{esc(it["title"])}</a></p>\n'
                f'          <p class="pg-tags"><span class="pg-small">#{it["number"]}</span>{tags}</p></div>\n'
                f'        <p class="pg-action"><a href="{url}">{"See it" if section == "Done" else "Vote on GitHub"} →</a></p>\n'
                f'      </li>')
        body = "\n".join(rows) if rows else '      <li class="pg-item pg-empty"><p class="pg-body">Nothing here yet.</p></li>'
        parts.append(
            f'  <section class="pg-section" id="{section.lower()}" aria-labelledby="h-{section.lower()}">\n'
            f'    <div class="pg-section-head"><h2 class="pg-h2" id="h-{section.lower()}">{section}</h2>'
            f'<p class="pg-body">{esc(INTRO[section])}</p></div>\n'
            f'    <ol class="pg-items">\n{body}\n    </ol>\n  </section>')
    return TEMPLATE.replace("{{DATE}}", esc(date)).replace("{{SECTIONS}}", "\n".join(parts)).replace("{{IDEAS}}", IDEAS)


