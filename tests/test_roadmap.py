"""ROADMAP.md and the site's roadmap page come from tools/roadmap.py, which reads the `roadmap` issues. The committed
files must be what it writes, and it must run with no network from a recorded answer (tests/fixtures/roadmap_issues.json,
synthetic issues, two pages back to back as `gh api --paginate` prints them)."""

import importlib.util
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests" / "fixtures" / "roadmap_issues.json"
SECTIONS = ["Now", "Next", "Later", "Done"]
ITEM = re.compile(r"^- 👍 (\d+) · \[(.+)\]\(https://github\.com/ballerine-io/pointe/issues/(\d+)\) \(#(\d+)\)( · .+)?$")

spec = importlib.util.spec_from_file_location("roadmap", ROOT / "tools" / "roadmap.py")
roadmap = importlib.util.module_from_spec(spec)
spec.loader.exec_module(roadmap)


def read_markdown(text: str) -> tuple[str, dict[str, list[tuple[int, int]]]]:
    """(the votes date, {section: [(issue, votes), ...]}), failing on anything out of shape."""
    lines = text.splitlines()
    assert lines[0].startswith("<!-- Generated by tools/roadmap.py"), "ROADMAP.md is generated: python3 tools/roadmap.py"
    assert lines[1] == "# Roadmap"
    date = re.search(r"^Votes as of (\d{4}-\d{2}-\d{2})\.$", text, re.M)
    assert date, "the date the votes were read"
    heads = [line[3:] for line in lines if line.startswith("## ")]
    assert heads == ["How it works", *SECTIONS]
    by, section = {}, None
    for line in lines:
        if line.startswith("## "):
            section = line[3:]
            by.setdefault(section, [])
        elif line.startswith("- 👍") and section in SECTIONS:
            m = ITEM.match(line)
            assert m, f"item line out of shape: {line}"
            assert m[3] == m[4], f"the link and the number name the same issue: {line}"
            by[section].append((int(m[3]), int(m[1])))
    for section in SECTIONS:
        votes = [v for _, v in by[section]]
        assert votes == sorted(votes, reverse=True), f"{section} is sorted by votes, most first"
    numbers = [n for s in SECTIONS for n, _ in by[s]]
    assert len(numbers) == len(set(numbers)), "an issue appears once"
    return date[1], {s: by[s] for s in SECTIONS}


def read_page(text: str) -> tuple[str, dict[str, list[tuple[int, int]]]]:
    date = re.search(r"Votes as of (\d{4}-\d{2}-\d{2}):", text)[1]
    by = {}
    for section in SECTIONS:
        block = re.search(rf'<section class="pg-section" id="{section.lower()}".*?</section>', text, re.S)[0]
        by[section] = [(int(n), int(v)) for v, n in re.findall(
            r'<p class="pg-votes"><span>(\d+)</span>.*?<span class="pg-small">#(\d+)</span>', block, re.S)]
    return date, by


def test_roadmap_md_is_well_formed():
    read_markdown((ROOT / "ROADMAP.md").read_text())


def test_the_site_page_shows_what_roadmap_md_shows():
    page = ROOT / "site" / "pointe" / "roadmap" / "index.html"
    assert read_page(page.read_text()) == read_markdown((ROOT / "ROADMAP.md").read_text()), \
        "regenerate both together: python3 tools/roadmap.py"


@pytest.fixture
def built(tmp_path, monkeypatch):
    """The generator run on the fixture, with every subprocess (so `gh`, and the network) refused."""
    def refuse(*a, **k):
        raise AssertionError("tools/roadmap.py --from must not run a process or reach the network")
    monkeypatch.setattr(roadmap.subprocess, "run", refuse)
    monkeypatch.setattr(sys, "argv", ["roadmap.py", "--from", str(FIXTURE), "--date", "2031-02-03", "--out", str(tmp_path)])
    roadmap.main()
    return (tmp_path / "ROADMAP.md").read_text(), (tmp_path / "site" / "pointe" / "roadmap" / "index.html").read_text()


def test_the_generator_runs_offline_from_the_fixture_and_sorts_by_votes(built):
    md, page = built
    date, by = read_markdown(md)
    assert date == "2031-02-03"
    assert by == {
        "Now": [(102, 9), (101, 3)],
        "Next": [(103, 1)],
        "Later": [(104, 5), (105, 5)],  # no horizon label is Later; a tie goes by issue number
        "Done": [(106, 7)],             # closed as completed; 107 (not planned), 108 (a pull request), 109 (no label) are out
    }
    assert read_page(page) == (date, by)


def test_tags_and_open_to_contributors_are_shown(built):
    md, page = built
    assert "(#101) · area/daemon · help wanted" in md
    assert "(#105) · platform/linux · good first issue" in md
    assert '<span class="pg-tag pg-tag--open">good first issue</span>' in page


def test_an_issue_title_cannot_inject_markup(built):
    md, page = built
    line = next(line for line in md.splitlines() if "(#103)" in line)
    assert "<script>" not in md and "&lt;script&gt;" in line
    assert r"\[with\](a link) and \*stars\*" in line, "brackets and emphasis are escaped in the link text"
    assert "<script>alert" not in page and "&lt;script&gt;alert(1)&lt;/script&gt;" in page
    assert "https://github.com/ballerine-io/pointe/issues/103" in page


def test_the_page_loads_nothing_and_links_only_github_and_itself(built):
    _, page = built
    assert not re.search(r"<(?:script|link|img|iframe|source|video|audio)\b[^>]*\b(?:src|href)=[\"'](?:https?:)?//", page)
    hosts = set(re.findall(r'href="https://([^/"]+)', page))
    assert hosts <= {"github.com"}, hosts


def test_the_same_answer_writes_the_same_files(built, tmp_path, monkeypatch):
    out = tmp_path / "again"
    monkeypatch.setattr(sys, "argv", ["roadmap.py", "--from", str(FIXTURE), "--date", "2031-02-03", "--out", str(out)])
    roadmap.main()
    assert ((out / "ROADMAP.md").read_text(), (out / "site" / "pointe" / "roadmap" / "index.html").read_text()) == built
